"""Generates jumbo_worker/contracts/ (pydantic v2 models) from packages/schema/json.

Run through `npm run codegen` from the repo root, which first re-exports the JSON Schemas from zod.
The output is committed, and CI fails when it drifts from the schemas.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMAS = ROOT / "packages" / "schema" / "json"
OUT = ROOT / "worker" / "jumbo_worker" / "contracts"

# Contract name -> module name.
CONTRACTS = {
    "PanelsDoc": "panels_doc",
    "ScriptDoc": "script_doc",
    "AudioManifest": "audio_manifest",
    "EpisodeSpec": "episode_spec",
    "MemoryDelta": "memory_delta",
    "LedgerEvent": "ledger_event",
    "SessionTicket": "session_ticket",
}

HEADER = "# Generated by worker/scripts/codegen.py from packages/schema/json. Do not edit; run `npm run codegen`.\n"

OPTIONS = [
    "--input-file-type", "jsonschema",
    "--output-model-type", "pydantic_v2.BaseModel",
    "--target-python-version", "3.10",
    "--use-annotated",
    "--field-constraints",
    "--use-standard-collections",
    "--use-union-operator",
    "--enum-field-as-literal", "all",
    "--use-double-quotes",
    "--use-schema-description",
    "--use-title-as-name",
    "--collapse-root-models",
    "--disable-timestamp",
    "--formatters", "builtin",
]


# Formats kept as plain, pattern-checked strings. Timestamps must survive a round trip byte for byte:
# the Rust ledger writes nanoseconds and hashes the exact text, which a Python datetime would truncate.
# base64 has no pydantic type and only produces a warning.
STRING_FORMATS = {"date-time", "base64"}


def plain_strings(node):
    if isinstance(node, dict):
        if node.get("format") in STRING_FORMATS:
            node = {k: v for k, v in node.items() if k != "format"}
        return {k: plain_strings(v) for k, v in node.items()}
    if isinstance(node, list):
        return [plain_strings(v) for v in node]
    return node


def generate(contract: str, module: str, scratch: Path) -> None:
    name = f"{contract}.schema.json"
    schema = plain_strings(json.loads((SCHEMAS / name).read_text(encoding="utf-8")))
    (scratch / name).write_text(json.dumps(schema), encoding="utf-8")
    out = OUT / f"{module}.py"
    subprocess.run(
        [sys.executable, "-m", "datamodel_code_generator", "--input", str(scratch / name), "--output", str(out), *OPTIONS],
        check=True,
    )
    out.write_text(HEADER + out.read_text(encoding="utf-8"), encoding="utf-8")


def write_catalog() -> None:
    catalog = json.loads((SCHEMAS / "presets.catalog.json").read_text(encoding="utf-8"))
    # json.dumps gives double-quoted literals that are also valid Python for plain text.
    q = json.dumps
    lines = [
        HEADER,
        '"""Preset vocabulary from packages/schema (PRESET_CATALOG, MULTI_PANEL_PRESETS)."""',
        "",
        f"SCHEMA_VERSION = {catalog['schema_version']}",
        "",
        "PRESET_NAMES: tuple[str, ...] = (",
        *[f"    {q(p['name'])}," for p in catalog["presets"]],
        ")",
        "",
        "# Presets that lay out 2-3 panels. Every other preset takes exactly one.",
        f"MULTI_PANEL_PRESETS: frozenset[str] = frozenset({{{', '.join(q(n) for n in sorted(catalog['multi_panel_presets']))}}})",
        "",
        "# Name and description of every preset, for the Director's system prompt.",
        "PRESET_CATALOG: tuple[dict[str, str], ...] = (",
        *[f'    {{"name": {q(p["name"])}, "description": {q(p["description"], ensure_ascii=False)}}},' for p in catalog["presets"]],
        ")",
        "",
    ]
    (OUT / "catalog.py").write_text("\n".join(lines), encoding="utf-8")


def write_init() -> None:
    lines = [
        HEADER,
        '"""Typed contracts shared with the desktop app and Remotion. Cross-field rules live in `rules`."""',
        "",
        "from .catalog import MULTI_PANEL_PRESETS, PRESET_CATALOG, PRESET_NAMES, SCHEMA_VERSION",
        *[f"from .{module} import {contract}" for contract, module in CONTRACTS.items()],
        "",
        "__all__ = [",
        *[f'    "{name}",' for name in sorted([*CONTRACTS, "MULTI_PANEL_PRESETS", "PRESET_CATALOG", "PRESET_NAMES", "SCHEMA_VERSION"])],
        "]",
        "",
    ]
    (OUT / "__init__.py").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as scratch:
        for contract, module in CONTRACTS.items():
            generate(contract, module, Path(scratch))
            print(f"wrote worker/jumbo_worker/contracts/{module}.py")
    write_catalog()
    write_init()
    print("wrote worker/jumbo_worker/contracts/catalog.py and __init__.py")


if __name__ == "__main__":
    main()
